int mnm_smb_accepted(const uint8_t *r, size_t len, int smb1)
{
	if (smb1) {
		/* [MS-CIFS] 2.2.4.52.2: after the transport header (4) and the SMB
		 * header (32) the word count, then the index of the chosen dialect;
		 * 0xFFFF means none of the offered ones. */
		if (len < 39 || r[4] != 0xff || r[5] != 'S' || r[6] != 'M' || r[7] != 'B' || r[36] < 1)
			return 0;
		return (r[37] | r[38] << 8) != 0xffff;
	}
	/* [MS-SMB2] 2.2.1: the status of the SMB2 header at offset 8; 0 is success. */
	if (len < 16 || r[4] != 0xfe || r[5] != 'S' || r[6] != 'M' || r[7] != 'B')
		return 0;
	return r[12] == 0 && r[13] == 0 && r[14] == 0 && r[15] == 0;
}

static int identify_smb(const uint8_t *r, size_t len)
{
	return mnm_smb_accepted(r, len, len >= 5 && r[4] == 0xff);
}

/*
 * Every dialect on its own connection, in the order of the desktop program: a
 * server accepts or refuses one requested dialect in the status of its answer,
 * so only single requests tell which ones it offers. Each connection waits at
 * most 5 s, each answer 2 s, as in the desktop program; one read of up to
 * 1024 bytes. (The desktop program also sends a request with all dialects at
 * the end, whose answer it never evaluates; it is left out here.)
 */
static int run_smb(uint32_t address, uint16_t port, int timeout_ms, char *detail, size_t detail_len)
{
	static const struct {
		const uint8_t *packet;
		size_t len;
		const char *version;
	} dialects[] = {
		{ pkt_smb_smb1_negotiate, sizeof(pkt_smb_smb1_negotiate), "1.0" },
		{ pkt_smb_smb2_negotiate_2_0_2, sizeof(pkt_smb_smb2_negotiate_2_0_2), "2.0.2" },
		{ pkt_smb_smb2_negotiate_2_1, sizeof(pkt_smb_smb2_negotiate_2_1), "2.1" },
		{ pkt_smb_smb2_negotiate_3_0, sizeof(pkt_smb_smb2_negotiate_3_0), "3.0" },
		{ pkt_smb_smb2_negotiate_3_0_2, sizeof(pkt_smb_smb2_negotiate_3_0_2), "3.0.2" },
		{ pkt_smb_smb2_negotiate_3_1_1, sizeof(pkt_smb_smb2_negotiate_3_1_1), "3.1.1" },
	};
	char versions[64] = "";
	(void)timeout_ms;
	/* Direct TCP only (445); on 139 SMB needs a NetBIOS session first. */
	if (port == 139)
		return 0;
	for (size_t i = 0; i < sizeof(dialects) / sizeof(dialects[0]); i++) {
		uint8_t answer[1024];
		int fd;
		if (mnm_tcp_connect(address, port, 5000, &fd) != MNM_CONNECTED)
			continue;
		ssize_t n = mnm_send_all(fd, dialects[i].packet, dialects[i].len, 2000) == 0
			? mnm_recv_once(fd, answer, sizeof(answer), 2000) : -1;
		close(fd);
		if (n > 0 && mnm_smb_accepted(answer, (size_t)n, i == 0)) {
			size_t used = strlen(versions);
			snprintf(versions + used, sizeof(versions) - used, "%s%s", used ? ", " : "", dialects[i].version);
		}
	}
	if (!versions[0])
		return 0;
	snprintf(detail, detail_len, "Versions: %s", versions);
	return 1;
}

