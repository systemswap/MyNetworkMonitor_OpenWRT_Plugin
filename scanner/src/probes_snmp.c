/* The request IDs: one counter for the process from a random start, kept in
 * the range that the library encodes in four bytes (as in almost all of its
 * requests), so that the packets keep their length. */
static uint32_t counter;

static void seed(void)
{
	uint32_t r;
	if (getrandom(&r, sizeof(r), 0) != (ssize_t)sizeof(r))
		r = (uint32_t)time(NULL);
	counter = r;
}

static uint32_t next_id(void)
{
	static pthread_once_t once = PTHREAD_ONCE_INIT;
	pthread_once(&once, seed);
	uint32_t c = __atomic_fetch_add(&counter, 1, __ATOMIC_RELAXED);
	return 0x01000000u + c % 0x7effffffu;   /* 0x01000000 to 0x7ffffffe */
}

/* Sends one request with a new ID and waits up to wait_ms for its answer.
 * Returns the number of values, -1 for an answer that is not the right one
 * (or reports an error), -2 if nothing came. */
static int ask(int fd, const uint8_t *packet, size_t len, int wait_ms, struct mnm_snmp_value *values, size_t max)
{
	uint8_t req[128], answer[1500];
	uint32_t id = next_id();
	if (len > sizeof(req))
		return -1;
	memcpy(req, packet, len);
	req[ID_AT] = (uint8_t)(id >> 24), req[ID_AT + 1] = (uint8_t)(id >> 16);
	req[ID_AT + 2] = (uint8_t)(id >> 8), req[ID_AT + 3] = (uint8_t)id;
	if (send(fd, req, len, 0) != (ssize_t)len)
		return -1;
	ssize_t n = mnm_recv_once(fd, answer, sizeof(answer), wait_ms);
	if (n == -2)
		return -2;
	if (n <= 0)
		return -1;
	return mnm_snmp_parse(answer, (size_t)n, id, values, max);
}

static int contains_ci(const char *hay, const char *needle)
{
	size_t n = strlen(needle);
	for (; *hay; hay++)
		if (strncasecmp(hay, needle, n) == 0)
			return 1;
	return 0;
}

void mnm_snmp_describe(const struct mnm_snmp_info *s, char *out, size_t outlen)
{
	static const char *const labels[] = { "Name", "Descr", "Location", "Contact", "Serial", "MAC" };
	const char *values[] = { s->name, s->descr, s->location, s->contact, s->serial, s->macs };
	char part[320];
	out[0] = '\0';
	for (size_t i = 0; i < 6; i++) {
		if (!values[i][0])
			continue;
		snprintf(part, sizeof(part), "%s: %s", labels[i], values[i]);
		mnm_detail_add(out, outlen, part);
	}
}

/* Takes a value, cut to the field (the JSON output keeps only whole UTF-8 characters). */
static void copy_value(char *dst, size_t cap, const struct mnm_snmp_value *v)
{
	if (!v->present || cap == 0)
		return;
	size_t n = strlen(v->text);
	if (n >= cap)
		n = cap - 1;
	memcpy(dst, v->text, n);
	dst[n] = '\0';
}

/*
 * The procedure of the desktop program: the system group (name, description,
 * location, contact) in one SNMPv1 request, 2 s; without an answer the device
 * has no SNMP for "public". Then the serial number of a printer, then the
 * hardware addresses of interfaces 1 to 50 one by one, 2 s each - here ending
 * at the first request that gets no answer at all, where the desktop program
 * would wait up to 100 s. Zebra printers and WAGO controllers are asked for
 * their own name and serial number over SNMPv2c (1 s, two attempts).
 */
static int run_snmp(uint32_t address, uint16_t port, int timeout_ms, char *detail, size_t detail_len)
{
	struct mnm_snmp_value v[4];
	struct mnm_snmp_info s;
	(void)timeout_ms;
	memset(&s, 0, sizeof(s));
	int fd = mnm_udp_socket(address, port);
	if (fd < 0)
		return 0;
	int n = ask(fd, pkt_snmp_get_system_v1_public, sizeof(pkt_snmp_get_system_v1_public), 2000, v, 4);
	if (n <= 0) {
		close(fd);
		return 0;
	}
	copy_value(s.name, sizeof(s.name), &v[0]);
	if (n > 1)
		copy_value(s.descr, sizeof(s.descr), &v[1]);
	if (n > 2)
		copy_value(s.location, sizeof(s.location), &v[2]);
	if (n > 3)
		copy_value(s.contact, sizeof(s.contact), &v[3]);
	if (ask(fd, pkt_snmp_get_serial_v1_public, sizeof(pkt_snmp_get_serial_v1_public), 2000, v, 1) > 0)
		copy_value(s.serial, sizeof(s.serial), &v[0]);
	for (int i = 0; i < 50; i++) {
		int r = ask(fd, pkt_snmp_ifphysaddress[i], 45, 2000, v, 1);
		if (r == -2)
			break;
		if (r <= 0 || v[0].raw_len != 6 || !memcmp(v[0].raw, "\0\0\0\0\0\0", 6))
			continue;
		char mac[18];
		snprintf(mac, sizeof(mac), "%02x-%02x-%02x-%02x-%02x-%02x", v[0].raw[0], v[0].raw[1], v[0].raw[2],
			 v[0].raw[3], v[0].raw[4], v[0].raw[5]);
		if (!strstr(s.macs, mac) && strlen(s.macs) + 22 < sizeof(s.macs)) {
			size_t used = strlen(s.macs);
			snprintf(s.macs + used, sizeof(s.macs) - used, "%s%s", used ? " / " : "", mac);
		}
	}
	int zebra = contains_ci(s.descr, "Zebra Technologies"), wago = contains_ci(s.descr, "wago");
	for (int attempt = 0; attempt < 2 && (zebra || wago); attempt++) {
		int r = zebra ? ask(fd, pkt_snmp_get_zebra_v2c_public, sizeof(pkt_snmp_get_zebra_v2c_public), 1000, v, 2)
			      : ask(fd, pkt_snmp_get_wago_v2c_public, sizeof(pkt_snmp_get_wago_v2c_public), 1000, v, 1);
		if (r > 0) {
			if (zebra) {
				copy_value(s.name, sizeof(s.name), &v[0]);
				if (r > 1)
					copy_value(s.serial, sizeof(s.serial), &v[1]);
			} else {
				copy_value(s.serial, sizeof(s.serial), &v[0]);
			}
			break;
		}
		usleep(30 * 1000);
	}
	close(fd);
	mnm_snmp_describe(&s, detail, detail_len);
	return 1;
}

static int identify_snmp(const uint8_t *r, size_t len)
{
	return len >= 2 && r[0] == 0x30;
}

const struct mnm_probe mnm_probes_snmp[] = {
	{ "snmp", "SNMP", pkt_snmp_get_system_v1_public, sizeof(pkt_snmp_get_system_v1_public), NULL, identify_snmp,
	  NULL, run_snmp, MNM_UDP, NULL, NULL },
	{ NULL, NULL, NULL, 0, NULL, NULL, NULL, NULL, MNM_TCP, NULL, NULL },
};
