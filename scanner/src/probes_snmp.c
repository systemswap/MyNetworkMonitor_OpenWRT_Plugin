/* Reads one TLV at *off (X.690: one tag byte, short or long length up to four
 * bytes). Returns 1 with the tag and the value, 0 if it does not fit. */
static int tlv(const uint8_t *r, size_t len, size_t *off, uint8_t *tag, const uint8_t **value, size_t *vlen)
{
	size_t o = *off;
	if (o + 2 > len)
		return 0;
	*tag = r[o++];
	size_t l = r[o++];
	if (l & 0x80) {
		size_t bytes = l & 0x7f;
		if (bytes == 0 || bytes > 4 || o + bytes > len)
			return 0;
		l = 0;
		while (bytes--)
			l = l << 8 | r[o++];
	}
	if (l > len - o)
		return 0;
	*value = r + o;
	*vlen = l;
	*off = o + l;
	return 1;
}

static int integer(const uint8_t *v, size_t n, long long *out)
{
	if (n == 0 || n > 8)
		return 0;
	long long x = (v[0] & 0x80) ? -1 : 0;
	for (size_t i = 0; i < n; i++)
		x = (long long)((unsigned long long)x << 8 | v[i]);
	*out = x;
	return 1;
}

/* Whether the bytes are UTF-8 text without control characters (tab and line
 * breaks allowed). */
static int is_utf8(const uint8_t *s, size_t n)
{
	for (size_t i = 0; i < n;) {
		uint8_t c = s[i];
		size_t extra;
		if (c < 0x80)
			extra = 0;
		else if ((c & 0xe0) == 0xc0)
			extra = 1;
		else if ((c & 0xf0) == 0xe0)
			extra = 2;
		else if ((c & 0xf8) == 0xf0)
			extra = 3;
		else
			return 0;
		if ((c < 0x20 && c != '\t' && c != '\r' && c != '\n') || c == 0x7f)
			return 0;
		for (size_t k = 1; k <= extra; k++)
			if (i + k >= n || (s[i + k] & 0xc0) != 0x80)
				return 0;
		i += extra + 1;
	}
	return 1;
}

/* A value as text, as the desktop program shows it: printable text as it is,
 * other octet strings as text if they are UTF-8 (the desktop program turns
 * their hex form back into UTF-8), else as hex; numbers in decimal, object
 * identifiers and addresses dotted. */
static void value_text(uint8_t tag, const uint8_t *v, size_t n, struct mnm_snmp_value *out)
{
	long long x;
	size_t used = 0;
	out->text[0] = '\0';
	out->present = 1;
	switch (tag) {
	case 0x04: {   /* OCTET STRING */
		int printable = 1;
		for (size_t i = 0; i < n; i++)
			printable &= v[i] == 0x09 || v[i] == 0x0a || v[i] == 0x0d || (v[i] >= 0x20 && v[i] <= 0x7e);
		out->raw_len = n < sizeof(out->raw) ? n : sizeof(out->raw);
		memcpy(out->raw, v, out->raw_len);
		if ((printable || is_utf8(v, n)) && n) {
			size_t k = 0;
			for (size_t i = 0; i < n && k + 1 < sizeof(out->text); i++)
				out->text[k++] = (v[i] == '\t' || v[i] == '\r' || v[i] == '\n') ? ' ' : (char)v[i];
			out->text[k] = '\0';
		} else {
			for (size_t i = 0; i < n && used + 4 < sizeof(out->text); i++)
				used += (size_t)snprintf(out->text + used, sizeof(out->text) - used, "%s%02x", i ? " " : "", v[i]);
		}
		break;
	}
	case 0x02: case 0x41: case 0x42: case 0x43: case 0x46:   /* INTEGER, Counter32, Gauge32, TimeTicks, Counter64 */
		if (tag != 0x02 && n > 0 && n <= 9) {
			unsigned long long u = 0;
			for (size_t i = 0; i < n; i++)
				u = u << 8 | v[i];
			snprintf(out->text, sizeof(out->text), "%llu", u);
		} else if (integer(v, n, &x)) {
			snprintf(out->text, sizeof(out->text), "%lld", x);
		}
		break;
	case 0x40:   /* IpAddress */
		if (n == 4)
			snprintf(out->text, sizeof(out->text), "%u.%u.%u.%u", v[0], v[1], v[2], v[3]);
		break;
	case 0x06: {   /* OBJECT IDENTIFIER */
		unsigned long arc = 0;
		for (size_t i = 0; i < n && used + 12 < sizeof(out->text); i++) {
			arc = arc << 7 | (v[i] & 0x7f);
			if (v[i] & 0x80)
				continue;
			if (used == 0)
				used += (size_t)snprintf(out->text, sizeof(out->text), "%lu.%lu", arc < 80 ? arc / 40 : 2,
							 arc < 80 ? arc % 40 : arc - 80);
			else
				used += (size_t)snprintf(out->text + used, sizeof(out->text) - used, ".%lu", arc);
			arc = 0;
		}
		break;
	}
	default:   /* NULL, noSuchObject, noSuchInstance, endOfMibView: no value */
		out->present = 0;
		break;
	}
}

int mnm_snmp_parse(const uint8_t *r, size_t len, uint32_t id, struct mnm_snmp_value *values, size_t max)
{
	size_t off = 0, n = 0, inner = 0, vlen;
	const uint8_t *v;
	uint8_t tag;
	long long x;

	memset(values, 0, max * sizeof(*values));
	if (!tlv(r, len, &off, &tag, &v, &vlen) || tag != 0x30)
		return -1;
	const uint8_t *msg = v;
	size_t mlen = vlen;
	if (!tlv(msg, mlen, &inner, &tag, &v, &vlen) || tag != 0x02 ||                   /* version */
	    !tlv(msg, mlen, &inner, &tag, &v, &vlen) || tag != 0x04 ||                   /* community */
	    !tlv(msg, mlen, &inner, &tag, &v, &vlen) || (tag != 0xa2 && tag != 0xa8))    /* Response or Report */
		return -1;
	const uint8_t *pdu = v;
	size_t plen = vlen, p = 0;
	if (!tlv(pdu, plen, &p, &tag, &v, &vlen) || tag != 0x02 || !integer(v, vlen, &x) || x != (long long)id)
		return -1;
	if (!tlv(pdu, plen, &p, &tag, &v, &vlen) || tag != 0x02 || !integer(v, vlen, &x) || x != 0)   /* error-status */
		return -1;
	if (!tlv(pdu, plen, &p, &tag, &v, &vlen) || tag != 0x02 ||                                       /* error-index */
	    !tlv(pdu, plen, &p, &tag, &v, &vlen) || tag != 0x30)
		return -1;
	const uint8_t *list = v;
	size_t llen = vlen, q = 0;
	while (n < max && q < llen) {
		const uint8_t *bind, *oid, *val;
		size_t blen, olen, valen, b = 0;
		uint8_t vtag;
		if (!tlv(list, llen, &q, &tag, &bind, &blen) || tag != 0x30 ||
		    !tlv(bind, blen, &b, &tag, &oid, &olen) || tag != 0x06 || !tlv(bind, blen, &b, &vtag, &val, &valen))
			break;
		values[n].oid_len = olen < sizeof(values[n].oid) ? olen : sizeof(values[n].oid);
		memcpy(values[n].oid, oid, values[n].oid_len);
		value_text(vtag, val, valen, &values[n]);
		n++;
	}
	return (int)n;
}

